-- Register tables used by the live dashboards with Supabase Realtime.
do $$
begin
  if not exists (
    select 1 from pg_publication_tables
    where pubname = 'supabase_realtime' and schemaname = 'public' and tablename = 'orders'
  ) then
    alter publication supabase_realtime add table public.orders;
  end if;
  if not exists (
    select 1 from pg_publication_tables
    where pubname = 'supabase_realtime' and schemaname = 'public' and tablename = 'rider_gps_points'
  ) then
    alter publication supabase_realtime add table public.rider_gps_points;
  end if;
  if not exists (
    select 1 from pg_publication_tables
    where pubname = 'supabase_realtime' and schemaname = 'public' and tablename = 'cases'
  ) then
    alter publication supabase_realtime add table public.cases;
  end if;
  if not exists (
    select 1 from pg_publication_tables
    where pubname = 'supabase_realtime' and schemaname = 'public' and tablename = 'verdicts'
  ) then
    alter publication supabase_realtime add table public.verdicts;
  end if;
  if not exists (
    select 1 from pg_publication_tables
    where pubname = 'supabase_realtime' and schemaname = 'public' and tablename = 'support_tickets'
  ) then
    alter publication supabase_realtime add table public.support_tickets;
  end if;
end;
$$;

create or replace view public.open_order_positions as
select
  o.id,
  o.zone_id,
  o.status,
  o.is_late_flagged,
  coalesce(g.lat, m.lat) as lat,
  coalesce(g.lng, m.lng) as lng
from public.orders o
join public.merchants m on m.id = o.merchant_id
left join lateral (
  select lat, lng
  from public.rider_gps_points
  where order_id = o.id
  order by recorded_at desc
  limit 1
) g on true
where o.status in ('placed', 'preparing', 'ready', 'picked_up');
